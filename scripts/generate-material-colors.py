#!/usr/bin/env python3
"""Generate Saldomi Material 3 color schemes from design-preview/tokens/colors.json.

Run from any directory: python3 scripts/generate-material-colors.py
Use --check in CI to detect an outdated generated Kotlin file.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design-preview/tokens/colors.json"
OUTPUT = ROOT / "app/src/main/java/com/firkat/fillin/ui/theme/GeneratedMaterialColors.kt"
HEX = re.compile(r"#[0-9a-fA-F]{6}\Z")
IDENTIFIER = re.compile(r"[A-Za-z][A-Za-z0-9]*\Z")

# Material 3 role -> design token. Shared semantic roles intentionally feed
# multiple Material roles; the complete token set is exposed separately below.
MATERIAL_ROLES = {
    "primary": "primary",
    "onPrimary": "onPrimary",
    "primaryContainer": "primaryContainer",
    "onPrimaryContainer": "onPrimaryContainer",
    "inversePrimary": "inversePrimary",
    "secondary": "secondary",
    "onSecondary": "onSecondary",
    "secondaryContainer": "secondaryContainer",
    "onSecondaryContainer": "onSecondaryContainer",
    "tertiary": "tertiary",
    "onTertiary": "onTertiary",
    "tertiaryContainer": "tertiaryContainer",
    "onTertiaryContainer": "onTertiaryContainer",
    "background": "background",
    "onBackground": "textPrimary",
    "surface": "surface",
    "onSurface": "textPrimary",
    "surfaceVariant": "surfaceAlt",
    "onSurfaceVariant": "textSecondary",
    "surfaceTint": "primary",
    "surfaceDim": "surfaceDim",
    "surfaceBright": "surfaceBright",
    "surfaceContainerLowest": "surfaceContainerLowest",
    "surfaceContainerLow": "surfaceContainerLow",
    "surfaceContainer": "surfaceContainer",
    "surfaceContainerHigh": "surfaceContainerHigh",
    "surfaceContainerHighest": "surfaceContainerHighest",
    "inverseSurface": "inverseSurface",
    "inverseOnSurface": "inverseOnSurface",
    "outline": "borderStrong",
    "outlineVariant": "border",
    "error": "danger",
    "onError": "onDanger",
    "errorContainer": "dangerContainer",
    "onErrorContainer": "onDangerContainer",
    "primaryFixed": "primaryFixed",
    "primaryFixedDim": "primaryFixedDim",
    "onPrimaryFixed": "onPrimaryFixed",
    "onPrimaryFixedVariant": "onPrimaryFixedVariant",
    "secondaryFixed": "secondaryFixed",
    "secondaryFixedDim": "secondaryFixedDim",
    "onSecondaryFixed": "onSecondaryFixed",
    "onSecondaryFixedVariant": "onSecondaryFixedVariant",
    "tertiaryFixed": "tertiaryFixed",
    "tertiaryFixedDim": "tertiaryFixedDim",
    "onTertiaryFixed": "onTertiaryFixed",
    "onTertiaryFixedVariant": "onTertiaryFixedVariant",
    "scrim": "scrim",
}


def load_tokens(path: Path) -> tuple[dict[str, dict[str, str]], str]:
    raw = path.read_bytes()
    data = json.loads(raw)
    modes = {mode: data[mode] for mode in ("light", "dark")}
    if not all(isinstance(colors, dict) for colors in modes.values()):
        raise ValueError("light and dark must be token objects")
    if set(modes["light"]) != set(modes["dark"]):
        raise ValueError("light and dark must have identical token names")
    for mode, colors in modes.items():
        for name, value in colors.items():
            if not IDENTIFIER.fullmatch(name) or not isinstance(value, str) or not HEX.fullmatch(value):
                raise ValueError(f"Invalid {mode} token: {name}={value!r}")
        missing = set(MATERIAL_ROLES.values()) - set(colors)
        if missing:
            raise ValueError(f"Missing {mode} Material tokens: {', '.join(sorted(missing))}")
    return modes, hashlib.sha256(raw).hexdigest()


def color(value: str) -> str:
    return f"Color(0xFF{value[1:].upper()})"


def render(modes: dict[str, dict[str, str]], digest: str) -> str:
    names = sorted(modes["light"])
    lines = [
        "// Generated by scripts/generate-material-colors.py from design-preview/tokens/colors.json.",
        f"// Source sha256: {digest}",
        "// Do not edit manually; rerun the generator after changing the JSON tokens.",
        "package com.firkat.fillin.ui.theme",
        "",
        "import androidx.compose.material3.darkColorScheme",
        "import androidx.compose.material3.lightColorScheme",
        "import androidx.compose.runtime.Immutable",
        "import androidx.compose.ui.graphics.Color",
        "",
        "@Immutable",
        "data class SaldomiDesignColors(",
    ]
    lines.extend(f"    val {name}: Color," for name in names)
    lines += [")", ""]
    for mode, constructor in (("light", "lightColorScheme"), ("dark", "darkColorScheme")):
        title = mode.title()
        lines.append(f"val Saldomi{title}DesignColors = SaldomiDesignColors(")
        lines.extend(f"    {name} = {color(modes[mode][name])}," for name in names)
        lines += [")", ""]
        lines.append(f"val Saldomi{title}Colors = {constructor}(")
        lines.extend(
            f"    {role} = {color(modes[mode][token])},"
            for role, token in MATERIAL_ROLES.items()
        )
        lines += [")", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated Kotlin is missing or stale")
    args = parser.parse_args()
    modes, digest = load_tokens(SOURCE)
    generated = render(modes, digest)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            parser.error(f"{OUTPUT.relative_to(ROOT)} is stale; run this script without --check")
        print(f"Up to date: {OUTPUT.relative_to(ROOT)}")
        return
    OUTPUT.write_text(generated)
    print(f"Generated {OUTPUT.relative_to(ROOT)} from {SOURCE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
